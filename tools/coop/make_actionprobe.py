"""Writes CoD3Host/coop_actionprobe.cpp: a hook on every function of the game's scripted-action module
(0x824F0000..0x8250FFFF: the action definitions' parser sub_824F3308 lives there) that is not hooked
elsewhere. COD3_COOP_ACTIONPROBE=1 turns it on (off: one test of a flag per call).

usage: python -I tools/coop/make_actionprobe.py   (from the source root)
"""
import glob, os, re

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.join(root, "CoD3Host", "coop_actionprobe.cpp")
hooked = set()
for fn in glob.glob(os.path.join(root, "CoD3Host", "*.cpp")) + glob.glob(os.path.join(root, "CoD3Host", "*.h")):
    if os.path.abspath(fn) == os.path.abspath(out):
        continue
    s = open(fn, encoding="utf-8", errors="ignore").read()
    hooked |= set(re.findall(r"PPC_FUNC\(sub_([0-9A-F]{8})\)", s))
    hooked |= set(re.findall(r"^\s*[A-Z_0-9]+\(\s*(?:0x)?([0-9A-F]{8})\s*[,)]", s, re.M))
m = open(os.path.join(root, "CoD3RecompLib", "ppc", "ppc_func_mapping.cpp")).read()
addrs = sorted(set(re.findall(r"\{ 0x(8(?:24F|250)[0-9A-F]{4}), sub_", m)))
addrs = [a for a in addrs if a not in hooked]

lines = []
w = lines.append
w("// GENERATED by tools/coop/make_actionprobe.py: do not edit by hand.")
w("// (0.5.972) The scripted-action probe: COD3_COOP_ACTIONPROBE=1. Every function of 0x824F0000..0x8250FFFF not")
w("// hooked elsewhere counts its calls; the first call of each is logged with its arguments, and once a second the")
w("// functions that became active (none of their calls in the 10 seconds before) are listed with the host's place:")
w("// what runs when the scripts start a wall hop, a struggle, a live grenade, a vehicle ...")
w("#ifndef COD3_MP")
w('#include "kernel.h"')
w('#include "coop.h"')
w("#include <chrono>")
w("#include <cstdio>")
w("#include <cstdlib>")
w("#include <cstring>")
w("#include <string>")
w("")
w("namespace")
w("{")
w("    // on in a co-op session (host or joining copy, a friend connected) unless COD3_COOP_ACTIONPROBE=0; =1 always")
w("    const int g_apEnv = []() { const char* t = getenv(\"COD3_COOP_ACTIONPROBE\"); return t ? (t[0] == '1' ? 1 : 0) : -1; }();")
w("    bool g_apOn = g_apEnv == 1;")
w("    int g_apChecks = 0;")
w("    constexpr int ApCount = %d;" % len(addrs))
w("    const uint32_t g_apAddr[ApCount] = {")
for i in range(0, len(addrs), 8):
    w("        " + ", ".join("0x" + a for a in addrs[i:i + 8]) + ",")
w("    };")
w("    uint32_t g_apHits[ApCount];")
w("    int64_t g_apLast[ApCount];")
w("    bool g_apSeen[ApCount];")
w("    int64_t g_apSec = -1;")
w("    int g_apLines = 0;")
w("    const auto g_apStart = std::chrono::steady_clock::now();")
w("")
w("    const char* ApWhat(uint8_t* base, uint32_t v)")
w("    {")
w("        if (!v) return \"\";")
w("        const uint32_t me = Coop::Me(base), rec = me ? Coop::Record(base, me) : 0, second = Coop::SecondPlayer();")
w("        if (v == me) return \"=PLAYER\";")
w("        if (v == rec) return \"=RECORD\";")
w("        if (second && v == second) return \"=JOINER\";")
w("        return \"\";")
w("    }")
w("")
w("    void ApReport(uint8_t* base, int64_t sec)")
w("    {")
w("        std::string list; int n = 0;")
w("        for (int i = 0; i < ApCount; i++)")
w("        {")
w("            if (!g_apHits[i]) continue;")
w("            if (g_apLast[i] < sec - 10 && n < 40) { char b[32]; snprintf(b, sizeof b, \" %08X x%u\", g_apAddr[i], g_apHits[i]); list += b; n++; }")
w("            g_apLast[i] = sec; g_apHits[i] = 0;")
w("        }")
w("        if (n && g_apLines < 8000)")
w("        {")
w("            g_apLines++;")
w("            const uint32_t me = Coop::Me(base);")
w("            float p[3] = {};")
w("            if (me) for (int k = 0; k < 3; k++) { const uint32_t u = Guest::Read32(base, me + 336 + 4 * k); memcpy(&p[k], &u, 4); }")
w("            printf(\"coop: action probe: t %lld at %.0f %.0f %.0f newly active:%s\\n\", (long long)sec, p[0], p[1], p[2], list.c_str());")
w("            fflush(stdout);")
w("        }")
w("    }")
w("")
w("    void ApHit(int i, PPCContext& ctx, uint8_t* base)")
w("    {")
w("        const int64_t sec = std::chrono::duration_cast<std::chrono::seconds>(std::chrono::steady_clock::now() - g_apStart).count();")
w("        if (g_apSec < 0) { g_apSec = sec; for (int k = 0; k < ApCount; k++) g_apLast[k] = -1000; }")
w("        if (sec != g_apSec) { ApReport(base, g_apSec); g_apSec = sec; }")
w("        g_apHits[i]++;")
w("        if (!g_apSeen[i] && g_apLines < 8000)")
w("        {")
w("            g_apSeen[i] = true; g_apLines++;")
w("            printf(\"coop: action probe: first %08X t %lld r3 %08X%s r4 %08X%s r5 %08X%s r6 %08X%s lr %08llX\\n\", g_apAddr[i], (long long)sec,")
w("                ctx.r3.u32, ApWhat(base, ctx.r3.u32), ctx.r4.u32, ApWhat(base, ctx.r4.u32), ctx.r5.u32, ApWhat(base, ctx.r5.u32),")
w("                ctx.r6.u32, ApWhat(base, ctx.r6.u32), (unsigned long long)ctx.lr);")
w("            fflush(stdout);")
w("        }")
w("    }")
w("")
w("    // a co-op session: looked at once every 4096 calls till on")
w("    inline bool ApOn()")
w("    {")
w("        if (g_apOn) return true;")
w("        if (g_apEnv != -1 || (++g_apChecks & 4095)) return false;")
w("        if ((Coop::IsHost() || Coop::IsJoin()) && Coop::PeerConnected()) { g_apOn = true; printf(\"coop: action probe: on (a co-op session; COD3_COOP_ACTIONPROBE=0 turns it off)\\n\"); fflush(stdout); }")
w("        return g_apOn;")
w("    }")
w("}")
w("")
w("#define COOP_AP(i, addr) \\")
w("    extern \"C\" PPC_FUNC(__imp__sub_##addr); \\")
w("    PPC_FUNC(sub_##addr) { if (ApOn()) ApHit(i, ctx, base); __imp__sub_##addr(ctx, base); }")
for i, a in enumerate(addrs):
    w("COOP_AP(%d, %s)" % (i, a))
w("")
w("#endif")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out, len(addrs), "hooks")
